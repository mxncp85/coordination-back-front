-- Requetes des clients de la guilde.
-- Montants en bronze (entiers).
-- Statuts : NOUVELLE -> EQUIPE_VALIDEE -> EN_COURS -> REUSSIE | ECHOUEE, ou REJETEE.

CREATE TABLE requete (
                         id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nom             VARCHAR(150) NOT NULL,
                         description     TEXT         NOT NULL,
                         duree_jours     INT          NOT NULL CHECK (duree_jours >= 1),
                         date_peremption DATE         NOT NULL,
                         prime_bronze    BIGINT       NOT NULL CHECK (prime_bronze >= 1),
                         commanditaire   VARCHAR(150) NOT NULL,
                         exp_recommandee INT          NOT NULL DEFAULT 0 CHECK (exp_recommandee >= 0),
                         xp_gagnee       INT          NOT NULL DEFAULT 0 CHECK (xp_gagnee >= 0),
                         statut          VARCHAR(20)  NOT NULL DEFAULT 'NOUVELLE'
                             CHECK (statut IN ('NOUVELLE', 'EQUIPE_VALIDEE', 'EN_COURS', 'REUSSIE', 'ECHOUEE', 'REJETEE')),
                         date_depart     DATE,
                         date_cloture    DATE
);

CREATE INDEX idx_requete_statut          ON requete (statut);
CREATE INDEX idx_requete_date_peremption ON requete (date_peremption);